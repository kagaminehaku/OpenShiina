# Writes src/text/UnicodeTables.inc: what text/Unicode needs to put text in Normalization Form C
# and to split it into text elements as .NET's string.Normalize and StringInfo do (ScnGaiji, a
# translation's letters), from Python's unicodedata:
#   kCombining  - code point ranges and their canonical combining class (non-zero only)
#   kDecompose  - canonical decompositions (code point, first, second; second 0 for one)
#   kCompose    - the pairs NFC composes (first, second, composite)
#   kExtend     - ranges that extend the text element before them (marks Mn, Me, Mc, ZWNJ, ZWJ,
#                 the emoji modifiers)
#   kControl    - ranges of controls and format characters (each its own element)
#   python gen_unicode.py <out.inc>
import sys
import unicodedata

MAX = 0x110000


def ranges(predicate):
    out, start = [], None
    for cp in range(MAX + 1):
        hit = cp < MAX and predicate(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def main():
    combining = []
    start = None
    for cp in range(MAX + 1):
        c = unicodedata.combining(chr(cp)) if cp < MAX else 0
        if start is not None and (c != start[1] or cp == MAX):
            combining.append((start[0], cp - 1, start[1]))
            start = None
        if c and start is None:
            start = (cp, c)
    decompose, compose = [], []
    for cp in range(MAX):
        if 0xAC00 <= cp <= 0xD7A3:
            continue  # Hangul syllables: by their formula
        d = unicodedata.decomposition(chr(cp))
        if not d or d.startswith('<'):
            continue
        parts = [int(x, 16) for x in d.split()]
        decompose.append((cp, parts[0], parts[1] if len(parts) > 1 else 0))
        if len(parts) == 2 and unicodedata.normalize('NFC', chr(parts[0]) + chr(parts[1])) == chr(cp):
            compose.append((parts[0], parts[1], cp))
    compose.sort()
    extend = ranges(lambda cp: unicodedata.category(chr(cp)) in ('Mn', 'Me', 'Mc') or cp in (0x200C, 0x200D) or 0x1F3FB <= cp <= 0x1F3FF)
    control = ranges(lambda cp: (unicodedata.category(chr(cp)) in ('Cc', 'Cf', 'Zl', 'Zp') and cp not in (0x200C, 0x200D)))
    lines = ['// Generated by tools/gen_unicode.py (Unicode %s): do not edit.' % unicodedata.unidata_version]
    lines.append('constexpr CombiningRange kCombining[] = {')
    lines += ['    {0x%X, 0x%X, %d},' % r for r in combining]
    lines.append('};')
    lines.append('constexpr Decomposition kDecompose[] = {')
    lines += ['    {0x%X, 0x%X, 0x%X},' % d for d in decompose]
    lines.append('};')
    lines.append('constexpr Composition kCompose[] = {')
    lines += ['    {0x%X, 0x%X, 0x%X},' % c for c in compose]
    lines.append('};')
    lines.append('constexpr CodeRange kExtend[] = {')
    lines += ['    {0x%X, 0x%X},' % r for r in extend]
    lines.append('};')
    lines.append('constexpr CodeRange kControl[] = {')
    lines += ['    {0x%X, 0x%X},' % r for r in control]
    lines.append('};')
    with open(sys.argv[1], 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


main()
